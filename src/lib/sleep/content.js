// tool pages themselves (pointing at further-dead /blog/<slug> hrefs) — never a real routable
// page. Kept as an empty array (matching PERSONAL_FINANCE_GUIDES's existing convention) so
// getSleepGuideBySlug and any future guide investment keep a stable API.
export const SLEEP_GUIDES = [];

export function getSleepToolBySlug(slug) {
  return SLEEP_TOOLS.find((tool) => tool.slug === slug) || null;
}

export function getRelatedSleepTools(slug) {
  const tool = getSleepToolBySlug(slug);
  if (!tool) return [];
  return (tool.relatedToolSlugs || []).map((item) => getSleepToolBySlug(item)).filter(Boolean);
}

export function getSleepGuideBySlug(slug) {
  return SLEEP_GUIDES.find((guide) => guide.slug === slug) || null;
}

export { SLEEP_MODES };
